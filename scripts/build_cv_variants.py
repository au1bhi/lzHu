#!/usr/bin/env python3
"""Generate audience-specific bilingual CVs; optionally compile published PDFs."""
import argparse
import json
import shutil
import subprocess
from compile_cv import compiled_cv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CV_DIR = ROOT / 'cv-latex'
VARIANT_DIR = CV_DIR / 'variants'
PDF_DIR = ROOT / 'assets' / 'pdf' / 'variants'

# Tune each language independently: translated text occupies different space.
# Font size, baseline, and section spacing preserve readable one-page layouts.
APPLICATION_LAYOUTS = {
    'international': {'color': '234E70', 'en': (10.1, 11.7, 5), 'zh': (10.5, 13.6, 6)},
    'training': {'color': '146A65', 'en': (10.2, 11.9, 5), 'zh': (10.5, 13.5, 6)},
    'engineering': {'color': '245D49', 'en': (10.3, 12, 5), 'zh': (10.7, 13.8, 6)},
    'academic': {'color': '59466B', 'en': (10, 11.6, 5), 'zh': (10.3, 13, 5)},
}


def application_preamble(preamble, audience, language):
    layout = APPLICATION_LAYOUTS[audience]
    size, baseline, spacing = layout[language]
    return preamble + rf'''
\usepackage{{xcolor}}
\definecolor{{cvaccent}}{{HTML}}{{{layout['color']}}}
\renewcommand{{\normalsize}}{{\fontsize{{{size}}}{{{baseline}}}\selectfont}}
\linespread{{1}}\selectfont
\titleformat{{\section}}{{\normalsize\bfseries\color{{cvaccent}}}}{{}}{{0pt}}{{}}[\vspace{{-1pt}}\titlerule]
\titlespacing*{{\section}}{{0pt}}{{{spacing}pt}}{{3pt}}
'''


def tex(text, language):
    if language == 'en':
        text = text.replace('’', "'").replace('“', '``').replace('”', "''")
    replacements = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%',
                    '$': r'\$', '#': r'\#', '_': r'\_', '{': r'\{',
                    '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}
    return ''.join(replacements.get(char, char) for char in text)


def education(language):
    if language == 'zh':
        return r'''\section{教育经历}
\begin{tabularx}{\textwidth}{@{}Y>{\raggedleft\arraybackslash}p{0.24\textwidth}@{}}
  \textbf{泉州信息工程学院} & \textit{2023--2027（预计）} \\
  软件工程（中外合作办学） & GPA: 3.10/4.00 \\[0.5pt]
  \multicolumn{2}{@{}l@{}}{\textbf{美国宾州滑石大学（Slippery Rock University）}} \\
  信息系统（Information Systems），理学学士（在读，预计 2027） & GPA: 3.583/4.000
\end{tabularx}
{\footnotesize\itshape 中美 4+0 双学位联合培养本科项目，全程在中国完成培养，经中华人民共和国教育部正式批准认可。}
'''
    return r'''\section{Education}
\begin{tabularx}{\textwidth}{@{}Y>{\raggedleft\arraybackslash}p{0.23\textwidth}@{}}
  \textbf{Quanzhou University of Information Engineering} & \textit{2023--2027 (expected)} \\
  Software Engineering (Sino-foreign Cooperation) & GPA: 3.10/4.00 \\[0.5pt]
  \multicolumn{2}{@{}l@{}}{\textbf{Slippery Rock University}} \\
  Information Systems, BS (in progress; expected 2027) & GPA: 3.583/4.000
\end{tabularx}
{\footnotesize\itshape Sino-American 4+0 dual-degree program conducted in China; approved by the Ministry of Education of China.}
'''


def render(data, audience, language):
    variant = data['variants'][audience]
    base = CV_DIR / ('cv-zh.tex' if language == 'zh' else 'cv.tex')
    preamble = base.read_text().split(r'\begin{document}', 1)[0]
    if language == 'zh':
        preamble = preamble.replace('胡力中 - 个人简历', f"胡力中 - {variant['label']['zh']}简历")
        preamble = preamble.replace('pdfsubject={个人简历}',
                                    'pdfsubject={' + variant['label']['zh'] + '简历}')
    else:
        preamble = preamble.replace('Lizhong Hu - Curriculum Vitae',
                                    'Lizhong Hu - ' + tex(variant['label']['en'], language) + ' CV')
        preamble = preamble.replace('pdfsubject={Academic curriculum vitae}',
                                    'pdfsubject={' + tex(variant['label']['en'], language) + ' CV}')
    application = audience in APPLICATION_LAYOUTS
    if application:
        preamble = application_preamble(preamble, audience, language)
    esc = lambda text: tex(text, language)
    chunks = ['% Generated by scripts/build_cv_variants.py from cv-latex/variants.json.\n',
              '% Edit the bilingual content source, then regenerate.\n', preamble,
              '\\begin{document}\n\\RaggedRight\n\\setlength{\\emergencystretch}{1em}\n']
    name = '胡力中' if language == 'zh' else 'Lizhong Hu'
    website = '个人网站' if language == 'zh' else 'Website'
    name_style = r'\fontsize{23}{25}\selectfont\bfseries\color{cvaccent}' if application else r'\LARGE\bfseries'
    chunks.append(r'\begin{center}' + '\n' + '{' + name_style + ' ' + name + '}\\par\n'
                  + r'\vspace{2pt}\small' + '\n'
                  + r'\href{https://au1bhi.com}{' + website + '}'
                  + r'\enspace$\vert$\enspace\href{mailto:admin@au1bhi.com}{admin@au1bhi.com}'
                  + r'\enspace$\vert$\enspace\href{https://github.com/au1bhi}{GitHub}'
                  + r'\enspace$\vert$\enspace\href{https://codeforces.com/profile/Au1Bhi}{Codeforces}'
                  + r'\enspace$\vert$\enspace\href{https://www.linkedin.com/in/lizhong-hu-686b9b34a}{LinkedIn}'
                  + '\n')
    if application:
        chunks.append('\\par\\vspace{4pt}{\\small\\bfseries\\color{cvaccent} '
                      + esc(variant['focus'][language]) + '}\n')
    chunks.append('\\end{center}\n\\vspace{-4pt}\n')
    chunks.append('\\section{' + ('个人简介' if language == 'zh' else 'Profile') + '}\n'
                  + esc(variant['profile'][language]) + '\n\n')
    chunks.append(education(language))
    if 'interests' in variant:
        chunks.append('\\section{' + ('研究方向与兴趣' if language == 'zh' else 'Research Interests')
                      + '}\n' + esc(variant['interests'][language]) + '\n')

    def awards():
        chunks.append('\\section{' + ('程序设计竞赛与获奖' if language == 'zh'
                                      else 'Competitive Programming & Awards').replace('&', r'\&') + '}\n')
        chunks.append('\\begin{itemize}\n')
        for award in data['awards']:
            chunks.append('  \\item ' + esc(award[language]) + '\n')
        chunks.append('\\end{itemize}\n')

    if audience == 'training':
        awards()
    def render_entry(item):
        title = esc(item['title'][language])
        if 'url' in item:
            title = '\\href{' + item['url'] + '}{' + title + '}'
        chunks.append('\\entry{' + title + '}{' + esc(item['date'][language]) + '}\n')
        if 'subtitle' in item:
            chunks.append('\\textit{' + esc(item['subtitle'][language]) + '}\n')
        links = []
        for resource in item.get('resources', []):
            label, url = resource[language]
            link = '\\href{' + url + '}{' + esc(label) + '}'
            links.append('\\mbox{' + link + '}' if item.get('resources_inline') else link)
        chunks.append('\\begin{itemize}\n')
        for index, bullet in enumerate(item['bullets']):
            label = ('\\textbf{' + esc(bullet['label'][language]) + '} '
                     if 'label' in bullet else '')
            inline_links = (' \\allowbreak\\enspace{\\small ' + ' \\enspace$\\vert$\\enspace '.join(links) + '}'
                            if links and item.get('resources_inline')
                            and index == len(item['bullets']) - 1 else '')
            chunks.append('  \\item ' + label + esc(bullet[language]) + inline_links + '\n')
        chunks.append('\\end{itemize}\n')
        if 'note' in item:
            chunks.append('{\\small ' + esc(item['note'][language]) + '}\\par\n')
        if 'event_groups' in item:
            chunks.append('\\textit{' + esc(item['event_intro'][language]) + '}\\par\n'
                          + '\\begin{itemize}\n')
            for group in item['event_groups']:
                chunks.append('  \\item \\textbf{' + str(group['year']) + ':} '
                              + esc(group[language]) + '\n')
            chunks.append('\\end{itemize}\n')
        if links and not item.get('resources_inline'):
            chunks.append('{\\small ' + ' \\enspace$\\vert$\\enspace '.join(links) + '}\\par\n')

    for section in variant['sections']:
        chunks.append('\\section{' + esc(section['title'][language]) + '}\n')
        for key in section['entries']:
            render_entry(data['entries'][key])
    if audience != 'training':
        awards()
    chunks.append('\\section{' + ('技术技能' if language == 'zh' else 'Technical Skills') + '}\n')
    for key in variant['skills']:
        label, value = data['skills'][key][language]
        chunks.append('\\skillrow{' + esc(label) + '}{' + esc(value) + '}\n')
    if 'resources' in variant:
        section = variant['resources']
        chunks.append('\\section{' + esc(section['title'][language]) + '}\n')
        for key in section['entries']:
            render_entry(data['entries'][key])
    chunks.append('\\end{document}\n')
    return ''.join(chunks)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compile', action='store_true', help='Compile and copy all PDFs into assets/pdf')
    parser.add_argument('--audience', choices=['international', 'training', 'engineering', 'academic'])
    parser.add_argument('--language', choices=['zh', 'en'])
    args = parser.parse_args()
    data = json.loads((CV_DIR / 'variants.json').read_text())
    for audience in ([args.audience] if args.audience else data['variants']):
        for language in ([args.language] if args.language else ['zh', 'en']):
            stem = f'cv-{language}'
            source_dir = VARIANT_DIR / audience
            source_dir.mkdir(parents=True, exist_ok=True)
            (source_dir / f'{stem}.tex').write_text(render(data, audience, language))
            if args.compile:
                with compiled_cv(source_dir / f'{stem}.tex', language) as pdf:
                    info = subprocess.check_output(['pdfinfo', str(pdf)], text=True)
                    pages = int(next(line.split(':', 1)[1] for line in info.splitlines()
                                     if line.startswith('Pages:')))
                    if pages != 1:
                        raise SystemExit(f'{source_dir.relative_to(ROOT)}/{stem}.tex produces {pages} pages; '
                                         'adjust its content or APPLICATION_LAYOUTS before publishing.')
                    target_dir = PDF_DIR / audience
                    target_dir.mkdir(parents=True, exist_ok=True)
                    target = target_dir / f'Lizhong_Hu_CV_{language}.pdf'
                    shutil.copyfile(pdf, target)
                if audience == 'engineering' and language == 'zh':
                    shutil.copyfile(target, target_dir / '胡力中_工程岗位简历.pdf')
                print(f'Built {target.relative_to(ROOT)}', flush=True)
            else:
                print(f'Generated {(source_dir / (stem + ".tex")).relative_to(ROOT)}')


if __name__ == '__main__':
    main()
